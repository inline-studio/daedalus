#!/usr/bin/env node
// Vendors the browser builds of the web-UI's markdown stack into a TS module.
//
// The web channel serves a single self-contained HTML shell with no external
// requests, and the build is `tsc` only (it copies no non-TS assets). So the
// minified library sources are embedded as base64 string constants in
// src/channels/web-vendor.ts, which tsc carries into dist; web.ts decodes them
// and serves them at /vendor/*.js. base64 sidesteps the backtick/${} escaping
// that raw minified JS would trip over.
//
// Re-run after bumping the marked / dompurify versions in package.json:
//   npm install && node scripts/vendor-web-libs.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(resolve(root, p));
const pkgVersion = (name) =>
  JSON.parse(read(`node_modules/${name}/package.json`)).version;

const libs = [
  { name: "marked", file: "node_modules/marked/lib/marked.umd.js", konst: "MARKED_UMD_JS" },
  { name: "dompurify", file: "node_modules/dompurify/dist/purify.min.js", konst: "DOMPURIFY_MIN_JS" },
];

let out =
  "// GENERATED by scripts/vendor-web-libs.mjs — do not edit by hand.\n" +
  "// Browser builds of the web-UI markdown stack, base64-embedded so `tsc`\n" +
  "// carries them into dist and web.ts can serve them at /vendor/*.js.\n" +
  `// marked ${pkgVersion("marked")} (window.marked) + DOMPurify ${pkgVersion("dompurify")} (window.DOMPurify).\n\n`;

for (const { name, file, konst } of libs) {
  const b64 = read(file).toString("base64");
  out += `// ${name} ${pkgVersion(name)} — ${file}\n`;
  out += `const ${konst}_B64 =\n  "${b64}";\n`;
  out += `export const ${konst} = Buffer.from(${konst}_B64, "base64").toString("utf8");\n\n`;
}

writeFileSync(resolve(root, "src/channels/web-vendor.ts"), out);
console.log("wrote src/channels/web-vendor.ts");
